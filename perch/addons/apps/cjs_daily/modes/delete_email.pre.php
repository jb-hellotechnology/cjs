<?php
    ini_set('display_errors', 1);
    ini_set('display_startup_errors', 1);
    error_reporting(E_ALL);
	$Emails = new CJS_Daily_Emails($API);

    $HTML = $API->get('HTML');
    $Form = $API->get('Form');
    $Form->set_name('delete');
	
    $message = false;

    //check that we have the ID of a thing, if not redirect back to the listing.
    if (isset($_GET['id']) && $_GET['id']!='') {
        $Email = $Emails->find($_GET['id'], true);
    }else{
        PerchUtil::redirect($API->app_path());
    }

    // if the confirmation of delete has been submitted this is a form post
      if ($Form->submitted()) {

        if (is_object($Email)) {

            if($Email->status() == 'scheduled'){
                // Generated by curl-to-PHP: http://incarnate.github.io/curl-to-php/
                $ch = curl_init();
                
                curl_setopt($ch, CURLOPT_URL, 'https://api.brevo.com/v3/emailCampaigns/'.$Email->campaignID().'/status');
                curl_setopt($ch, CURLOPT_RETURNTRANSFER, 1);
                curl_setopt($ch, CURLOPT_CUSTOMREQUEST, 'PUT');
                
                curl_setopt($ch, CURLOPT_POSTFIELDS, "{\"status\":\"suspended\"}");
                
                $headers = array();
                $headers[] = 'Accept: application/json';
                $headers[] = 'Api-Key: ' . (defined('CJS_BREVO_API_KEY') ? CJS_BREVO_API_KEY : '');
                $headers[] = 'Content-Type: application/json';
                curl_setopt($ch, CURLOPT_HTTPHEADER, $headers);
                
                $response = curl_exec($curl);
                $response = json_decode($response, true);
                if (curl_errno($ch)) {
                    echo 'Error:' . curl_error($ch);
                }
                curl_close($ch);
    
                if (empty($response)) {
                    // Run your function for the empty case
                    $Email->delete();
                    $message = $HTML->success_message('Email deleted.');
                }
                
                if (isset($response['message'])) {
                    $message = $HTML->failure_message("NOT DELETED: ".$response['message']);
                }
                
            }else{
                $curl = curl_init();
                
                curl_setopt_array($curl, [
                  CURLOPT_URL => "https://api.brevo.com/v3/emailCampaigns/".$Email->campaignID(),
                  CURLOPT_RETURNTRANSFER => true,
                  CURLOPT_ENCODING => "",
                  CURLOPT_MAXREDIRS => 10,
                  CURLOPT_TIMEOUT => 30,
                  CURLOPT_HTTP_VERSION => CURL_HTTP_VERSION_1_1,
                  CURLOPT_CUSTOMREQUEST => "DELETE",
                  CURLOPT_HTTPHEADER => [
                    "accept: application/json",
                    "api-key: " . (defined('CJS_BREVO_API_KEY') ? CJS_BREVO_API_KEY : '')
                  ],
                ]);
                
                $response = curl_exec($curl);
                $response = json_decode($response, true);
                $err = curl_error($curl);
                
                curl_close($curl);
                
                if (empty($response)) {
                    // Run your function for the empty case
                    $Email->delete();
                    $message = $HTML->success_message('Email deleted.');
                }
                
                if (isset($response['message'])) {
                    $message = $HTML->failure_message("NOT DELETED: ".$response['message']);
                }
            }

          }else{
              $message = $HTML->failure_message('Sorry, that email could not be deleted.');
          }
          
          
      }

